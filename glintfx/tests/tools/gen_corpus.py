note("png_interlaced.png", "PNG RGBA8 interlaced Adam7, 16x16")

# ---------------------------------------------------------------- (a) I/O e corrupcao
good = (OUT / "png_rgba8.png").read_bytes()

(OUT / "empty.png").write_bytes(b"")
note("empty.png", "arquivo de 0 byte")

(OUT / "text.png").write_bytes(b"isto nao e uma imagem, e texto puro\n" * 4)
note("text.png", "texto renomeado para .png")

(OUT / "truncated_half.png").write_bytes(good[: len(good) // 2])
note("truncated_half.png", "PNG real cortado exatamente na metade")

(OUT / "truncated_header_only.png").write_bytes(good[:33])
note("truncated_header_only.png", "PNG real: so assinatura + IHDR (sem IDAT)")

bad_crc = bytearray(good)
bad_crc[-5] ^= 0xFF  # corrompe o CRC do IEND
(OUT / "bad_crc_iend.png").write_bytes(bytes(bad_crc))
note("bad_crc_iend.png", "PNG com CRC do IEND corrompido")

bad_idat = bytearray(good)
# acha o IDAT e corrompe 1 byte do payload comprimido (quebra o zlib, IHDR fica valido)
i = bytes(bad_idat).find(b"IDAT")
bad_idat[i + 8] ^= 0xFF
(OUT / "bad_idat_payload.png").write_bytes(bytes(bad_idat))
note("bad_idat_payload.png", "PNG com payload do IDAT corrompido (header valido, zlib quebrado)")

huge_dim = bytearray(good)
struct.pack_into(">II", huge_dim, 16, 0x7FFFFFF0, 0x7FFFFFF0)  # w/h absurdos no IHDR
huge_dim[29:33] = struct.pack(">I", zlib.crc32(bytes(huge_dim[12:29])) & 0xFFFFFFFF)
(OUT / "png_huge_dims.png").write_bytes(bytes(huge_dim))
note("png_huge_dims.png", "PNG com w=h=0x7FFFFFF0 no IHDR (overflow de dimensao)")

zero_dim = bytearray(good)
struct.pack_into(">II", zero_dim, 16, 0, 0)
zero_dim[29:33] = struct.pack(">I", zlib.crc32(bytes(zero_dim[12:29])) & 0xFFFFFFFF)
(OUT / "png_zero_dims.png").write_bytes(bytes(zero_dim))
note("png_zero_dims.png", "PNG com w=h=0 no IHDR")

(OUT / "noperm.png").write_bytes(good)
os.chmod(OUT / "noperm.png", 0o000)
note("noperm.png", "PNG valido SEM permissao de leitura (chmod 000)")

(OUT / "adir.png").mkdir()
note("adir.png", "DIRETORIO com nome .png")

