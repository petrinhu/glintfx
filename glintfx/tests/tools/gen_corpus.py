"""Corpus enumerado para o review adversarial da fatia S1 (stbi_load -> glintfx::decode_image_file).

Enumera o espaco INTEIRO de:
  (a) modos de falha de I/O / arquivo hostil
  (b) tipos de PNG (color type x bit depth) que o req_comp=4 do stbi_load normalizava
  (c) formatos NAO-PNG (o STBI_ONLY_PNG antigo rejeitava; o glintfx compila PNG+JPEG+TGA)
  (d) dimensoes de borda
"""
import os
import random
import shutil
import struct
import zlib
from pathlib import Path

# Saida: argv[1] > env CORPUS_OUT > ./corpus ao lado deste script.
# Nada de caminho absoluto embutido: este arquivo e compartilhado entre projetos.
import sys
_default = Path(__file__).resolve().parent / "corpus"
OUT = Path(sys.argv[1] if len(sys.argv) > 1 else os.environ.get("CORPUS_OUT", _default))
if OUT.exists():
    shutil.rmtree(OUT)
OUT.mkdir(parents=True)

from PIL import Image


def png_chunk(tag: bytes, data: bytes) -> bytes:
    return (struct.pack(">I", len(data)) + tag + data
            + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF))


def raw_png(path: Path, w: int, h: int, color_type: int, bit_depth: int, rows: bytes,
            palette: bytes = b"", trns: bytes = b"") -> None:
    """Monta um PNG a mao (permite color types que o PIL nao expoe direto)."""
    ihdr = struct.pack(">IIBBBBB", w, h, bit_depth, color_type, 0, 0, 0)
    body = b"\x89PNG\r\n\x1a\n" + png_chunk(b"IHDR", ihdr)
    if palette:
        body += png_chunk(b"PLTE", palette)
    if trns:
        body += png_chunk(b"tRNS", trns)
    body += png_chunk(b"IDAT", zlib.compress(rows, 9))
    body += png_chunk(b"IEND", b"")
    path.write_bytes(body)


def scanlines(h: int, per_row: bytes) -> bytes:
    return b"".join(b"\x00" + per_row for _ in range(h))


made = []


def note(name: str, desc: str):
    made.append((name, desc))


# ---------------------------------------------------------------- (b) tipos de PNG
# color type 0 = grayscale, 2 = RGB, 3 = paletizado, 4 = gray+alpha, 6 = RGBA
raw_png(OUT / "png_gray8.png", 4, 4, 0, 8, scanlines(4, bytes([0, 64, 128, 255])))
note("png_gray8.png", "PNG grayscale 8-bit (color type 0), 4x4")

raw_png(OUT / "png_gray_alpha8.png", 4, 4, 4, 8,
        scanlines(4, bytes([10, 255, 20, 128, 30, 1, 40, 0])))
note("png_gray_alpha8.png", "PNG gray+alpha 8-bit (color type 4), 4x4")

raw_png(OUT / "png_rgb8.png", 4, 4, 2, 8,
        scanlines(4, bytes([255, 0, 0, 0, 255, 0, 0, 0, 255, 7, 8, 9])))
note("png_rgb8.png", "PNG RGB 8-bit SEM alpha (color type 2), 4x4")

pal = bytes([255, 0, 0, 0, 255, 0, 0, 0, 255, 9, 9, 9])
raw_png(OUT / "png_palette8.png", 4, 4, 3, 8, scanlines(4, bytes([0, 1, 2, 3])), palette=pal)
note("png_palette8.png", "PNG paletizado 8-bit (color type 3, PLTE), 4x4")

raw_png(OUT / "png_palette8_trns.png", 4, 4, 3, 8, scanlines(4, bytes([0, 1, 2, 3])),
        palette=pal, trns=bytes([255, 128, 0, 64]))
note("png_palette8_trns.png", "PNG paletizado + tRNS (alpha por indice), 4x4")

# ---------------------------------------------------------------------------
# PALETIZADO GRANDE: o unico caso do corpus capaz de ESGOTAR memoria, e o que
# dispara o A-1 (bad_alloc escapando do decode) sob `ulimit -v`.
#
# Por que PALETIZADO e nao RGBA8: aqui o buffer intermediario do stb tem 1
# byte por pixel (indice) e a saida tem 4 (RGBA), logo a copia extra do
# decode_image_file soma sobre o pico. Em RGBA8 o pico interno do proprio stb
# ja e 2x a saida e os dois caminhos EMPATAM -- um RGBA8 grande nao dispara o
# bug, e essa e a unica razao pela qual ele sobreviveu a duas provas de
# equivalencia byte-a-byte.
#
# 12000x12000 = 144 Mpx: 144 MB de indices, 576 MB de RGBA. Comprime para
# ~140 KB porque as linhas sao identicas (zlib mata a redundancia), entao o
# arquivo e pequeno e a EXPANSAO e enorme -- exatamente o que se quer para
# testar exaustao sem carregar fixture pesada.
_PAL_BIG = 12000
_pal_row = bytes([0] * (_PAL_BIG // 4) + [1] * (_PAL_BIG // 4)
                 + [2] * (_PAL_BIG // 4) + [3] * (_PAL_BIG - 3 * (_PAL_BIG // 4)))
raw_png(OUT / "png_pal_12000.png", _PAL_BIG, _PAL_BIG, 3, 8,
        scanlines(_PAL_BIG, _pal_row), palette=pal)
note("png_pal_12000.png",
     f"PNG paletizado {_PAL_BIG}x{_PAL_BIG} (144 Mpx, 576 MB decodificado) - DISPARA o A-1")

raw_png(OUT / "png_gray1.png", 8, 4, 0, 1, scanlines(4, bytes([0b10110010])))
note("png_gray1.png", "PNG grayscale 1 bit-per-pixel (sub-byte), 8x4")

raw_png(OUT / "png_gray4.png", 4, 4, 0, 4, scanlines(4, bytes([0x0F, 0xA5])))
note("png_gray4.png", "PNG grayscale 4 bits-per-pixel (sub-byte), 4x4")

raw_png(OUT / "png_rgb16.png", 2, 2, 2, 16,
        scanlines(2, struct.pack(">6H", 0xFFFF, 0x0000, 0x8000, 0x1234, 0x00FF, 0xFF00)))
note("png_rgb16.png", "PNG RGB 16 bits POR CANAL (color type 2, depth 16), 2x2")

raw_png(OUT / "png_rgba16.png", 2, 2, 6, 16,
        scanlines(2, struct.pack(">8H", 0xFFFF, 0, 0, 0x8080, 0, 0xFFFF, 0, 0xFFFF)))
note("png_rgba16.png", "PNG RGBA 16 bits POR CANAL (color type 6, depth 16), 2x2")

# RGBA 8 normal (controle) + alpha parcial
img = Image.new("RGBA", (4, 4))
img.putdata([(i * 16, 255 - i * 16, 128, (i * 17) % 256) for i in range(16)])
img.save(OUT / "png_rgba8.png")
note("png_rgba8.png", "PNG RGBA8 normal com alpha parcial (CONTROLE), 4x4")

